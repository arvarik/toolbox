// comes from. Change it here, run `npm run brand`, and commit what it writes.

/** Each part is one round-capped stroke in a 100-unit box. Kit faces right. */
export const PARTS = {
  dome: "M 12 60 C 11 40 23 25 40 25 C 57 25 70 37 72 58",
  body: "M 70.8 50 C 73.5 46.5 75.5 42 78.5 39 C 81.5 35.8 87.5 35 90.8 38 C 94 41 94.5 45.5 92.5 48.5 C 90.5 51.5 86.5 53.2 82.5 53.2 C 79 53.2 76 56.5 73.5 58.5 C 62 65 22 66.5 8 57",
  plates: "M 29.5 27.1 L 34 35 L 46 35 L 50.5 26.7 M 34 35 L 28 45 L 34 55 L 46 55 L 52 45 L 46 35",
  seams: "M 28 45 L 13.9 45 M 52 45 L 69.2 45 M 34 55 L 31.5 63.4 M 46 55 L 48.5 63.6",
  frontLeg: "M 57 63 C 57 68 58 72 60.5 75.5 C 62.5 78.3 67 78.6 70 77.6 C 72.5 76.8 72 74 70 72.5 C 67.5 70.6 66 67 65.5 62.5",
  backLeg: "M 23.5 63.5 C 23 68 21.5 72 18.5 75.5 C 16.5 78 12 78.6 9.5 77.4 C 7.2 76.3 7.8 74 9.8 72.5 C 12.5 70.5 14.2 66.5 14.8 61",
} as const;

export type Part = keyof typeof PARTS;

export const EYE = { cx: 85.5, cy: 43 } as const;

const ALL = Object.keys(PARTS) as Part[];

/**
 * One stroke cannot serve every size, so the mark has four masters. Each draws
 * the same paths with a stroke and an eye for the size a person sees. `scale`
 * is Kit's size in its box: on the tile for the icons, alone for the logo.
 */
export const MASTERS = {
  tiny: { stroke: 8.5, eye: 0, scale: 1, parts: ["dome", "body", "frontLeg", "backLeg"] as Part[] },
  small: { stroke: 5.2, eye: 2.8, scale: 0.88, parts: ["dome", "body", "frontLeg", "backLeg"] as Part[] },
  medium: { stroke: 4.4, eye: 2.6, scale: 0.8, parts: ALL },
  large: { stroke: 3.6, eye: 2.8, scale: 0.9, parts: ALL },
} as const;

export type Master = keyof typeof MASTERS;
export type Colors = { ink: string; eye: string };

/** Literals, because a favicon cannot read a CSS token. docs/brand/README.md maps each to its token. */
export const COLORS = {
  light: { ink: "#4338ca", eye: "#d97706" },
  dark: { ink: "#93a0ff", eye: "#fbbf24" },
  black: { ink: "#000000", eye: "#000000" },
  white: { ink: "#ffffff", eye: "#ffffff" },
} as const satisfies Record<string, Colors>;

export const GROUND = { light: "#f8f6f2", dark: "#09090b" } as const;

export const TILE = { from: "#4338ca", to: "#6366f1", ink: "#ffffff", eye: "#fbbf24" } as const;

const round = (n: number) => Math.round(n * 100) / 100;

/** Kit as an SVG group, shrunk about the middle by `scale` with the stroke and eye kept at full weight. */
function kit(master: Master, colors: Colors, scale: number): string {
  const m = MASTERS[master];
  const shift = round(50 * (1 - scale));
  const paths = m.parts.map((p) => `    <path d="${PARTS[p]}" />`);
  if (m.eye) {
    paths.push(`    <circle cx="${EYE.cx}" cy="${EYE.cy}" r="${round(m.eye / scale)}" fill="${colors.eye}" stroke="none" />`);
  }
  return [
    `  <g transform="translate(${shift} ${shift}) scale(${scale})" fill="none" stroke="${colors.ink}" stroke-width="${round(m.stroke / scale)}" stroke-linecap="round" stroke-linejoin="round">`,
    ...paths,
    "  </g>",
  ].join("\n");
}

const open = (note: string) =>
  [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" role="img" aria-label="Toolbox">`,
    "  <title>Toolbox</title>",
    `  <!-- ${note} Generated by scripts/brand/build.ts from scripts/brand/kit.ts. Do not edit. -->`,
  ].join("\n");

/** The logo: the `large` master alone, with no tile. */
export function markSvg(colors: Colors, note: string): string {
  return `${open(note)}\n${kit("large", colors, MASTERS.large.scale)}\n</svg>\n`;
}

/** Kit in white on the indigo tile, the master of every icon. Corners are 22 percent of the side. */
export function tileSvg(master: Master): string {
  return [
    open(`The ${master} master on the tile.`),
    '  <defs><linearGradient id="tile" x1="0" y1="0" x2="1" y2="1">',
    `    <stop offset="0" stop-color="${TILE.from}" /><stop offset="1" stop-color="${TILE.to}" />`,
    "  </linearGradient></defs>",
    '  <rect width="100" height="100" rx="22" fill="url(#tile)" />',
    kit(master, TILE, MASTERS[master].scale),
    "</svg>",
    "",
  ].join("\n");
}
